export type StackItem = {
  name: string
  slug?: string
}

export type StackSubCategory = {
  id: string
  name: { pt: string; en: string }
  items: StackItem[]
}

export type StackCategory = {
  id: string
  icon: string
  name: { pt: string; en: string }
  items?: StackItem[]
  subcategories?: StackSubCategory[]
}

export type StackDetailSection = {
  id: string
  title: { pt: string; en: string }
  items: string[]
}

export type StackDetail = {
  slug: string
  name: string
  icon: string
  description: { pt: string; en: string }
  sections: StackDetailSection[]
}

export function categoryItemCount(cat: StackCategory): number {
  if (cat.items) return cat.items.length
  if (cat.subcategories) return cat.subcategories.reduce((s, sub) => s + sub.items.length, 0)
  return 0
}

